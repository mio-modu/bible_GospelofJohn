/** 제3강 · PART 3 표적으로 영광을 드러내시다 (6:1~21) */
const { LAYOUT } = require("../../theme");
const { rows, statement, keyline, cardGrid, stats } = require("../../components");

const SECTION = "표적으로";

module.exports = function signs(pres) {
  const C = pres.SchemeColor;
  const M = LAYOUT.MARGIN;
  pres.addSection({ title: SECTION });
  const S = (masterName) => pres.addSlide({ masterName, sectionTitle: SECTION });

  const qtag = (s, text) =>
    s.addText(text, {
      x: 10.5, y: LAYOUT.TITLE_Y, w: 2.08, h: LAYOUT.TITLE_H, margin: 0, isTextBox: true,
      fontSize: 17, bold: true, align: "right", valign: "middle", color: C.accent1, objectName: "qtag",
    });

  // ── 구분
  {
    const s = S("DIVIDER");
    s.addText("03", { placeholder: "num" });
    s.addText("표적으로 영광을 드러내시다", { placeholder: "title" });
    s.addText("오병이어  ·  물 위를 걸으심   ·   요한복음 6:1~21", { placeholder: "body" });
  }

  // ── 오병이어
  {
    const s = S("CONTENT");
    s.addText("보리떡 다섯, 물고기 둘", { placeholder: "title" });
    qtag(s, "요 6:1~15");
    stats(
      s,
      pres,
      [
        { num: "5,000", label: "먹은 남자의 수" },
        { num: "5 + 2", label: "한 아이의 도시락" },
        { num: "12", label: "남은 조각 바구니" },
        { num: "4", label: "네 복음서 모두에 실린\n유일한 사건 (부활 제외)" },
      ],
      { y: 2.0, h: 2.2, numSize: 44, labelSize: 17 }
    );
    keyline(s, pres, { y: 4.7, h: 1.6, text: "실제로 일어난 사건입니다\n성육하신, 창조의 능력을 가지신 하나님의 아들이심을 보여 줍니다", fontSize: 26 });
    s.addNotes(
      "오병이어입니다. 부활을 제외하고 네 복음서 모두에 기록된 유일한 사건입니다. " +
        "그만큼 초대교회가 중요하게 여겼다는 뜻입니다.\n\n" +
        "요한복음만의 세부를 짚으십시오.\n" +
        "  · 6절 — '친히 어떻게 하실지를 아시고 빌립을 시험하고자 하심이라.' " +
        "이미 답을 가지고 물으십니다.\n" +
        "  · 7절 — 빌립의 계산. 이백 데나리온이면 노동자 200일치 품삯인데 그래도 부족합니다. " +
        "빌립은 계산을 했고, 계산의 결론은 '안 됩니다'였습니다.\n" +
        "  · 9절 — 안드레는 사람을 데려옵니다. 한 아이와 보리떡 다섯 개. " +
        "안드레도 '그것이 얼마나 되겠사옵나이까' 합니다. 그래도 가져왔습니다.\n" +
        "  · 보리떡은 가난한 사람의 양식입니다. 작고 초라한 것을 쓰십니다.\n" +
        "  · 12절 — '남은 조각을 거두고 버리는 것이 없게 하라.' " +
        "풍성하게 베푸시되 함부로 쓰지 않으십니다.\n\n" +
        "표적의 의미는 분명합니다. 무(無)에서 창조하시는 분, " +
        "곧 성육하신 창조의 능력을 가지신 하나님의 아들이심을 보여 줍니다.\n\n" +
        "비교 — 하늘에서 내려온 떡이라는 점에서 만나와 비슷하지만, " +
        "결정적 차이는 이 떡이 영생하게 하는 떡이라는 것입니다. 뒤의 6:49~51에서 다시 다룹니다."
    );
  }

  // ── 임금 삼으려 하다
  {
    const s = S("CONTENT_DARK");
    s.addText("그들은 임금으로 삼으려 했습니다", { placeholder: "title" });
    statement(s, pres, {
      y: 2.1, size: 36, dark: true,
      text: "“이는 참으로 세상에 오실 그 선지자라”\n그러나 그들이 원한 것은 다른 왕이었습니다",
      sub: "현재적 · 정치적 · 경제적인 왕\n로마로부터 해방시키고 우리를 영광스럽게 해 줄 지도자",
      ref: "요한복음 6:14~15",
    });
    keyline(s, pres, { y: 5.8, h: 0.88, text: "예수께서 다시 혼자 산으로 떠나 가시니라", fontSize: 27 });
    s.addNotes(
      "표적의 결과는 좋아 보입니다. 14절 — 사람들이 예수님을 '그 선지자', 곧 그리스도로 인정합니다.\n\n" +
        "그런데 15절에서 예수님이 피하십니다. '억지로 붙들어 임금으로 삼으려는 줄 아시고 " +
        "다시 혼자 산으로 떠나 가시니라.'\n\n" +
        "왜 피하셨습니까. 그들이 원한 왕이 달랐기 때문입니다. " +
        "현재적이고 정치적이고 경제적인 왕, 로마로부터 해방시켜 주고 " +
        "자기들을 영광스럽게 해 줄 지도자를 원했습니다.\n\n" +
        "표적까지 보고도 예수님을 자기 필요에 맞춰 재단한 것입니다. " +
        "오늘 아침 4부에서 다룰 '썩을 양식'이 여기서 시작됩니다.\n\n" +
        "Q   당신이 가진 예수님에 대한 상(像)은 어떤 것입니까? " +
        "내가 바라는 모습으로 그분을 그려 놓고 있지는 않습니까?"
    );
  }

  // ── 물 위를 걸으심
  {
    const s = S("CONTENT");
    s.addText("“내니 두려워하지 말라”", { placeholder: "title" });
    qtag(s, "요 6:16~21");
    const endY = rows(
      s,
      pres,
      [
        { tag: "상황", head: "이미 어두웠고, 예수는 아직 오시지 아니하셨더니", body: "큰 바람이 불어 파도가 일어나더라" },
        { tag: "표적", head: "바다 위로 걸어 배에 가까이 오심", body: "자연도 다스리시는 만물의 주이십니다" },
        { tag: "결과", head: "배는 곧 그들이 가려던 땅에 이르렀더라", body: "모셔들이자 목적지에 닿았습니다" },
      ],
      { y: 1.9, headSize: 26, bodySize: 19, tagW: 1.3, gap: 0.16 }
    );
    keyline(s, pres, { after: endY, y: 5.7, h: 0.92, text: "어둡고, 바람 불고, 아직 오시지 않은 것처럼 보이는 그 시간", fontSize: 26 });
    s.addNotes(
      "짧지만 깊은 본문입니다.\n\n" +
        "17절의 문장 구조를 보십시오. '이미 어두웠고 예수는 아직 그들에게 오시지 아니하셨더니.' " +
        "어둠이 먼저 오고, 바람이 불고, 주님은 아직 안 오십니다. " +
        "신앙 생활에서 누구나 겪는 그 시간입니다.\n\n" +
        "표적의 의미는 자연도 다스리시는 만물의 주 되심입니다. " +
        "구약에서 바다를 밟으시는 분은 하나님이십니다(욥 9:8, 시 77:19).\n\n" +
        "20절의 '내니'는 헬라어로 '에고 에이미(ἐγώ εἰμι)', 곧 '내가 그다'입니다. " +
        "출애굽기 3:14의 '나는 스스로 있는 자'와 같은 표현입니다. " +
        "단순한 자기 소개가 아니라 신적 선언입니다.\n\n" +
        "21절 — '이에 기뻐서 배로 영접하니 배는 곧 그들이 가려던 땅에 이르렀더라.' " +
        "모셔들이자 도착했습니다. 노를 저어 십여 리를 갔는데도 못 가던 길이었습니다.\n\n" +
        "Q   어려운 상황에서 예수님이 함께 계심을 깨닫고 안심했던 경험이 있습니까?"
    );
  }
};
