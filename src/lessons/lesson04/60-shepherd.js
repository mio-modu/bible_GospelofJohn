        "  **예수님** — 생명을 얻게 하고, 더 풍성히 얻게 하십니다. 주는 동사입니다.\n\n" +
        "Q   여러분은 어떻게 영적 양식을 얻습니까? (예배 · 체험 · 관계 · 응답)"
